import XCTest
import AppKit
@testable import Velopaste

final class ClipboardTests: XCTestCase {
    @MainActor
    private func withClipboard(_ body: (ClipboardStore, NSPasteboard) throws -> Void) rethrows {
        // A private pasteboard keeps tests away from the user's real clipboard and Keychain.
        let board = NSPasteboard.withUniqueName()
        defer { board.releaseGlobally() }
        let store = ClipboardStore(preview: true, pasteboard: board)
        store.deleteEverything()
        store.excludedApps = ""
        board.clearContents()
        try body(store, board)
    }
    @MainActor func testCaptureRealPasteboardTextAndRestoreRichFormats() throws {
        try withClipboard { store, board in
            let item = NSPasteboardItem()
            item.setString("Clipboard integration fixture", forType: .string)
            let rtf = Data("{\\rtf1\\ansi Clipboard integration fixture}".utf8)
            item.setData(rtf, forType: .rtf)
            XCTAssertTrue(board.writeObjects([item]))
            store.capture()
            let clip = try XCTUnwrap(store.history.items.first)
            XCTAssertEqual(clip.text, "Clipboard integration fixture")
            XCTAssertEqual(clip.formats[NSPasteboard.PasteboardType.rtf.rawValue], rtf)
            board.clearContents()
            XCTAssertTrue(store.copy(clip))
            XCTAssertEqual(board.string(forType: .string), clip.text)
            XCTAssertEqual(board.data(forType: .rtf), rtf)
            store.capture()
            XCTAssertEqual(store.history.items.count, 1, "Restored clips must not loop into history")
            XCTAssertTrue(store.copy(clip, plain: true))
            XCTAssertNil(board.data(forType: .rtf))
            XCTAssertEqual(board.string(forType: .string), clip.text)
        }
    }
    @MainActor func testConfidentialTemporaryAndGeneratedCopiesAreSkipped() {
        withClipboard { store, board in
            for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword", "app.velopaste.restored"] {
                let item = NSPasteboardItem()
                item.setString("Secret fixture", forType: .string)
                item.setString("1", forType: .init(marker))
                board.clearContents()
                XCTAssertTrue(board.writeObjects([item]))
                store.capture()
            }
            XCTAssertTrue(store.history.items.isEmpty)
        }
    }
    @MainActor func testPauseAndResumeDoesNotCapturePausedCopies() {
        withClipboard { store, board in
            store.isPaused = true
            board.setString("While paused", forType: .string)
            store.capture()
            store.isPaused = false
            store.capture()
            XCTAssertTrue(store.history.items.isEmpty)
            board.clearContents()
            board.setString("After resume", forType: .string)
            store.capture()
            XCTAssertEqual(store.history.items.map(\.text), ["After resume"])
        }
    }
    @MainActor func testExcludedSourceIsSkipped() {
        withClipboard { store, board in
            store.excludedApps = "test.secret-app"
            let item = NSPasteboardItem()
            item.setString("Excluded fixture", forType: .string)
            item.setString("test.secret-app", forType: .init("org.nspasteboard.source"))
            XCTAssertTrue(board.writeObjects([item]))
            store.capture()
            XCTAssertTrue(store.history.items.isEmpty)
        }
    }
    @MainActor func testCaptureAndRestoreImageBytes() throws {
        try withClipboard { store, board in
            let image = NSImage(size: NSSize(width: 24, height: 24))
            image.lockFocus()
            NSColor.systemPurple.setFill()
            NSBezierPath(rect: NSRect(x: 0, y: 0, width: 24, height: 24)).fill()
            image.unlockFocus()
            let bytes = try XCTUnwrap(image.tiffRepresentation)
            XCTAssertTrue(board.setData(bytes, forType: .tiff))
            store.capture()
            let clip = try XCTUnwrap(store.history.items.first)
            XCTAssertEqual(clip.kind, .image)
            XCTAssertNotNil(clip.previewImage)
            board.clearContents()
            XCTAssertTrue(store.copy(clip))
            XCTAssertEqual(board.data(forType: .tiff), bytes)
        }
    }
}

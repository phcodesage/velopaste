import AppKit
import SwiftUI
import Combine
import ApplicationServices

@MainActor
final class ClipboardStore: ObservableObject {
    @Published private(set) var history: History
    @Published var query = ""
    @Published var filter: ClipFilter = .all
    @Published var selectedID: UUID?
    @Published var mode: PanelMode = .clipboard
    @Published var showingSettings = false
    @Published var notice: String?
    @Published var storageWarning: String?
    @Published var shortcutWarning: String?
    @Published var isPaused = false {
        didSet { lastChange = pasteboard.changeCount }
    }
    @Published var capacity: Int {
        didSet { preferences.set(capacity, forKey: "capacity"); history.capacity = capacity; history.trim(); persist() }
    }
    @Published var remember: Bool {
        didSet { preferences.set(remember, forKey: "remember"); updatePersistence() }
    }
    @Published var autoPaste: Bool {
        didSet { preferences.set(autoPaste, forKey: "autoPaste") }
    }
    @Published var appearance: String {
        didSet { preferences.set(appearance, forKey: "appearance") }
    }
    @Published var shortcut: String {
        didSet { preferences.set(shortcut, forKey: "shortcut"); shortcutChanged?() }
    }
    @Published var excludedApps: String {
        didSet { preferences.set(excludedApps, forKey: "excludedApps") }
    }
    var shortcutChanged: (() -> Void)?
    var choose: ((Clip, Bool) -> Void)?
    var dismiss: (() -> Void)?
    let preview: Bool
    private let sessionOnly: Bool
    let preferences: UserDefaults
    private let pasteboard: NSPasteboard
    private var lastChange: Int
    private var timer: Timer?
    private var vault: Vault?
    private let diskQueue = DispatchQueue(label: "app.velopaste.vault", qos: .utility)
    private var pendingSave: DispatchWorkItem?
    private var noticeTask: Task<Void, Never>?

    enum PanelMode: String, CaseIterable {
        case clipboard = "Clipboard", emoji = "Emoji", symbols = "Symbols"
        var icon: String {
            switch self { case .clipboard: return "doc.on.clipboard"; case .emoji: return "face.smiling"; case .symbols: return "character" }
        }
    }
    var items: [Clip] { history.filtered(query: query, filter: filter) }
    var selected: Clip? { items.first { $0.id == selectedID } ?? items.first }
    var colorScheme: ColorScheme? { appearance == "Light" ? .light : appearance == "Dark" ? .dark : nil }
    var trusted: Bool { AXIsProcessTrusted() }
    var pasteEnabled: Bool { autoPaste && trusted }

    init(preview: Bool = false, pasteboard: NSPasteboard = .general, sessionOnly: Bool = false) {
        self.pasteboard = pasteboard
        self.sessionOnly = sessionOnly
        self.preview = preview
        preferences = preview || sessionOnly ? UserDefaults(suiteName: sessionOnly ? "app.velopaste.smoke" : "app.velopaste.preview")! : .standard
        let initialCapacity = preview ? 25 : (preferences.object(forKey: "capacity") as? Int ?? 25)
        capacity = initialCapacity
        remember = preview || sessionOnly ? false : (preferences.object(forKey: "remember") as? Bool ?? true)
        autoPaste = preferences.object(forKey: "autoPaste") as? Bool ?? true
        appearance = preview ? "Light" : (preferences.string(forKey: "appearance") ?? "System")
        shortcut = preferences.string(forKey: "shortcut") ?? "⌥V"
        excludedApps = preferences.string(forKey: "excludedApps") ?? "com.1password.1password\ncom.agilebits.onepassword7\ncom.apple.Passwords\ncom.bitwarden.desktop\ncom.apple.keychainaccess"
        history = History(capacity: initialCapacity)
        lastChange = pasteboard.changeCount
        if preview {
            history = History(items: Self.previewClips())
        } else {
            if remember { openVault() }
            timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
                MainActor.assumeIsolated { self?.capture() }
            }
        }
    }
    func capture() {
        let board = pasteboard
        guard board.changeCount != lastChange else { return }
        lastChange = board.changeCount
        guard !isPaused else { return }
        let types = Set((board.types ?? []).map(\.rawValue))
        let excludedTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping", "Pasteboard generator type", "app.velopaste.restored"]
        guard types.isDisjoint(with: excludedTypes) else { return }
        let front = NSWorkspace.shared.frontmostApplication
        let bundleID = board.string(forType: .init("org.nspasteboard.source")) ?? front?.bundleIdentifier ?? ""
        let exclusions = excludedApps.components(separatedBy: .whitespacesAndNewlines).filter { !$0.isEmpty }
        guard !exclusions.contains(bundleID) else { return }
        var formats: [String: Data] = [:]
        var bytes = 0
        for type in [NSPasteboard.PasteboardType.string, .rtf, .html, .png, .tiff] {
            if let data = board.data(forType: type) {
                bytes += data.count
                guard bytes <= History.itemLimit else { return }
                formats[type.rawValue] = data
            }
        }
        let hasImage = formats[NSPasteboard.PasteboardType.png.rawValue] != nil || formats[NSPasteboard.PasteboardType.tiff.rawValue] != nil
        let text = board.string(forType: .string) ?? ""
        guard hasImage || !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        let source = NSRunningApplication.runningApplications(withBundleIdentifier: bundleID).first?.localizedName ?? front?.localizedName ?? "Unknown app"
        let clip = Clip(text: text, formats: formats, kind: hasImage ? .image : Clip.classify(text), sourceName: source, sourceBundleID: bundleID)
        if history.insert(clip) { persist() }
    }
    func copy(_ clip: Clip, plain: Bool = false) -> Bool {
        let board = pasteboard
        let item = NSPasteboardItem()
        if plain && clip.kind != .image {
            item.setString(clip.text, forType: .string)
        } else {
            for (type, bytes) in clip.formats { item.setData(bytes, forType: .init(type)) }
            if !clip.text.isEmpty { item.setString(clip.text, forType: .string) }
        }
        item.setString("1", forType: .init("app.velopaste.restored"))
        item.setString(clip.sourceBundleID, forType: .init("org.nspasteboard.source"))
        board.clearContents()
        let success = board.writeObjects([item])
        lastChange = board.changeCount
        if !success { toast("Couldn't copy this item. Try again.") }
        return success
    }
    func chooseText(_ text: String) {
        let clip = Clip(text: text, formats: [NSPasteboard.PasteboardType.string.rawValue: Data(text.utf8)], kind: .text, sourceName: "Velopaste", sourceBundleID: "app.velopaste")
        choose?(clip, false)
    }
    func pin(_ clip: Clip) { history.pin(clip.id); persist() }
    func delete(_ clip: Clip) { history.remove(clip.id); persist() }
    func clear() { history.clear(); persist(); toast("History cleared. Pins kept.") }
    func deleteEverything() {
        history.clear(keepingPins: false)
        if vault == nil && !preview && !sessionOnly { removeSavedHistory() }
        persist()
        toast("All saved items deleted")
    }
    func moveSelection(_ delta: Int) {
        guard !items.isEmpty else { return }
        let index = items.firstIndex(where: { $0.id == selectedID }) ?? (delta > 0 ? -1 : items.count)
        selectedID = items[max(0, min(items.count - 1, index + delta))].id
    }
    func toast(_ text: String) {
        noticeTask?.cancel()
        notice = text
        noticeTask = Task { [weak self] in
            try? await Task.sleep(nanoseconds: 2_500_000_000)
            if !Task.isCancelled { self?.notice = nil }
        }
    }
    func requestAccessibility() {
        let options = [kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary
        _ = AXIsProcessTrustedWithOptions(options)
        NSWorkspace.shared.open(URL(string: "x-apple.systempreferences:com.apple.preference.security?Privacy_Accessibility")!)
    }
    func flush() {
        pendingSave?.cancel()
        if let vault, remember { let clips = history.items; diskQueue.sync { try? vault.write(clips) } }
    }
    private func openVault() {
        do {
            let candidate = try Vault()
            let saved = try candidate.read()
            history = History(items: saved, capacity: capacity)
            vault = candidate
            storageWarning = nil
        } catch {
            storageWarning = "Encrypted storage unavailable. History stays in memory for this session; existing saved data is untouched."
        }
    }
    private func updatePersistence() {
        guard !preview, !sessionOnly else { return }
        pendingSave?.cancel()
        if remember {
            // Preserve this session rather than replacing it with older saved history.
            if vault == nil {
                do { vault = try Vault(); storageWarning = nil }
                catch { storageWarning = "Keychain unavailable. History stays in memory." }
            }
            persist()
        } else {
            removeSavedHistory()
        }
    }
    private func removeSavedHistory() {
        pendingSave?.cancel()
        storageWarning = nil
        diskQueue.async { [weak self] in
            do {
                // Deletion must still work when Keychain access/decryption is unavailable.
                let url = try Vault.historyURL()
                if FileManager.default.fileExists(atPath: url.path) { try FileManager.default.removeItem(at: url) }
            } catch {
                Task { @MainActor in self?.storageWarning = "Couldn't remove saved history. Try again after checking file permissions." }
            }
        }
    }
    private func persist() {
        guard !preview, !sessionOnly, remember, let vault else { return }
        pendingSave?.cancel()
        let clips = history.items
        let work = DispatchWorkItem { [weak self] in
            do { try vault.write(clips) }
            catch { Task { @MainActor in self?.storageWarning = "Couldn't save history. New items remain in memory." } }
        }
        pendingSave = work
        diskQueue.asyncAfter(deadline: .now() + 0.35, execute: work)
    }
    private static func previewClips() -> [Clip] {
        func text(_ value: String, source: String, bundle: String, pinned: Bool = false, age: Double = 0) -> Clip {
            Clip(text: value, formats: ["public.utf8-plain-text": Data(value.utf8)], kind: Clip.classify(value), sourceName: source, sourceBundleID: bundle, createdAt: Date().addingTimeInterval(-age), pinned: pinned)
        }
        return [
            text("A little less searching.\nA lot more creating.", source: "Notes", bundle: "com.apple.Notes", age: 40),
            text("https://developer.apple.com/design/", source: "Safari", bundle: "com.apple.Safari", pinned: true, age: 180),
            text("const ideas = clipboard.history;\nreturn ideas.map(makeSomethingGreat);", source: "Visual Studio Code", bundle: "com.microsoft.VSCode", age: 420),
            text("The best tools get out of your way. ✨", source: "Notes", bundle: "com.apple.Notes", age: 800)
        ]
    }
}
